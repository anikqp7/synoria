const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { randomBytes } = require('node:crypto');
require('dotenv').config({ path: require('node:path').join(__dirname, '../.env'), quiet: true });
const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');

test('department-owned students, validation and role-based login', { timeout: 30000 }, async () => {
  process.env.SESSION_SECRET = randomBytes(48).toString('hex');
  let app;
  let server;
  try {
    await mongoose.connect(process.env.MONGODB_URI, { dbName: `thesis_student_test_${randomBytes(8).toString('hex')}`, serverSelectionTimeoutMS: 5000 });
    const Department = require('../src/models/department');
    const Student = require('../src/models/student');
    await Promise.all([Department.init(), Student.init()]);
    app = require('../src');
    server = app.listen(0, '127.0.0.1');
    await once(server, 'listening');
    const base = `http://127.0.0.1:${server.address().port}/api/auth`;
    const request = (route, body, cookie, method) => fetch(`${base}/${route}`, { method: method || (body ? 'POST' : 'GET'), headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: body ? JSON.stringify(body) : undefined });
    const password = 'department-password-123';
    const departments = await Department.create([
      { name: 'CSE', university: 'Test University', email: 'cse@example.edu', passwordHash: await bcrypt.hash(password, 12) },
      { name: 'EEE', university: 'Other University', email: 'eee@example.edu', passwordHash: await bcrypt.hash(password, 12) },
    ]);
    const cookieFor = response => response.headers.get('set-cookie').split(';')[0];
    const deptCookie = cookieFor(await request('login', { email: departments[0].email, password }));
    const otherCookie = cookieFor(await request('login', { email: departments[1].email, password }));
    const fields = { name: 'Dr. Ayesha', email: 'AYESHA@example.edu', phone: '+880 1712 345678', studentId: '2022-CSE-001', batch: '42', academicSession: '2022-2023', password: 'student-password-123', department: departments[1].id };
    assert.equal((await request('students')).status, 401);
    assert.equal((await request('students', fields)).status, 401);
    assert.equal((await request('students', { ...fields, phone: 'abc' }, deptCookie)).status, 400);
    assert.equal((await request('students', { ...fields, password: 'short' }, deptCookie)).status, 400);
    assert.equal((await request('students', { ...fields, email: { $ne: null } }, deptCookie)).status, 400);
    assert.equal((await request('students', { ...fields, studentId: '   ' }, deptCookie)).status, 400);
    const created = await request('students', fields, deptCookie);
    assert.equal(created.status, 201);
    const student = (await created.json()).student;
    assert.equal(student.email, 'ayesha@example.edu');
    assert.equal(student.passwordHash, undefined);
    const profile = await request(`students/${student.id}`, null, deptCookie);
    assert.equal(profile.status, 200);
    assert.equal((await profile.json()).student.email, 'ayesha@example.edu');
    assert.equal((await request(`students/${student.id}`, null, otherCookie)).status, 404);
    assert.equal((await request(`students/${student.id}`)).status, 401);
    assert.equal((await request('students/not-an-id', null, deptCookie)).status, 404);
    assert.equal((await request('students/000000000000000000000000', null, deptCookie)).status, 404);
    const saved = await Student.findById(student.id).select('+passwordHash');
    assert.equal(String(saved.department), departments[0].id);
    assert.notEqual(saved.passwordHash, fields.password);
    assert.equal(await bcrypt.compare(fields.password, saved.passwordHash), true);
    assert.equal((await request('students', fields, deptCookie)).status, 409);
    assert.equal((await request('students', { ...fields, email: 'different@example.edu' }, deptCookie)).status, 409);
    assert.equal((await (await request('students', null, deptCookie)).json()).students.length, 1);
    assert.equal((await (await request('students', null, otherCookie)).json()).students.length, 0);
    assert.equal((await request('students', { ...fields, email: 'other-department@example.edu' }, otherCookie)).status, 201);
    assert.equal((await request('login', { email: fields.email, password: fields.password, role: 'department' })).status, 401);
    assert.equal((await request('login', { email: fields.email, password: 'wrong', role: 'student' })).status, 401);
    assert.equal((await request('register', { ...fields, role: 'student' })).status, 400);
    const login = await request('login', { email: fields.email, password: fields.password, role: 'student' });
    assert.equal(login.status, 200);
    const user = (await login.json()).user;
    assert.equal(user.role, 'student');
    assert.equal(user.departmentId, departments[0].id);
    assert.equal(user.university, 'Test University');
    assert.equal(user.studentId, fields.studentId);
    assert.equal(user.batch, fields.batch);
    assert.equal(user.passwordHash, undefined);
    const studentCookie = cookieFor(login);
    assert.equal((await (await request('me', null, studentCookie)).json()).user.email, 'ayesha@example.edu');
    assert.equal((await request('students', null, studentCookie)).status, 403);
    assert.equal((await request(`students/${student.id}`, null, studentCookie)).status, 403);
    assert.equal((await request('students', fields, studentCookie)).status, 403);
    assert.equal((await request('supervisors', null, studentCookie)).status, 403);
    assert.equal((await request('supervisors', fields, studentCookie)).status, 403);

    const accountPath = `students/${student.id}`;
    assert.equal((await request(accountPath, { name: 'Intruder' }, otherCookie, 'PATCH')).status, 404);
    assert.equal((await request(accountPath, {}, otherCookie, 'DELETE')).status, 404);
    assert.equal((await request(accountPath, { name: 'Intruder' }, null, 'PATCH')).status, 401);
    assert.equal((await request(accountPath, { name: 'Intruder' }, studentCookie, 'PATCH')).status, 403);
    assert.equal((await request(accountPath, {}, studentCookie, 'DELETE')).status, 403);
    assert.equal((await request(accountPath, { email: { $ne: null } }, deptCookie, 'PATCH')).status, 400);
    assert.equal((await request(accountPath, { password: 'short' }, deptCookie, 'PATCH')).status, 400);
    const secondFields = { ...fields, email: 'second@example.edu', studentId: 'SECOND-ID' };
    assert.equal((await request('students', secondFields, deptCookie)).status, 201);
    assert.equal((await request(accountPath, { email: secondFields.email }, deptCookie, 'PATCH')).status, 409);
    assert.equal((await request(accountPath, { studentId: secondFields.studentId }, deptCookie, 'PATCH')).status, 409);
    const updated = await request(accountPath, { name: 'Updated Member', phone: '+8801999999999', password: '', department: departments[1].id, passwordHash: 'injected' }, deptCookie, 'PATCH');
    assert.equal(updated.status, 200);
    assert.equal((await updated.json()).student.name, 'Updated Member');
    const afterUpdate = await Student.findById(student.id).select('+passwordHash');
    assert.equal(String(afterUpdate.department), departments[0].id);
    assert.equal(afterUpdate.passwordHash, saved.passwordHash);
    const newPassword = 'updated-password-123';
    assert.equal((await request(accountPath, { password: newPassword }, deptCookie, 'PATCH')).status, 200);
    assert.equal((await request('login', { email: fields.email, password: fields.password, role: 'student' })).status, 401);
    const newLogin = await request('login', { email: fields.email, password: newPassword, role: 'student' });
    assert.equal(newLogin.status, 200);
    const newCookie = cookieFor(newLogin);
    assert.equal((await request(accountPath, {}, deptCookie, 'DELETE')).status, 200);
    assert.equal((await request(accountPath, null, deptCookie)).status, 404);
    assert.equal((await request('me', null, newCookie)).status, 401);
    assert.equal((await request('login', { email: fields.email, password: newPassword, role: 'student' })).status, 401);
    assert.equal((await request(accountPath, {}, deptCookie, 'DELETE')).status, 404);
    await request('logout', {}, studentCookie);
    assert.equal((await request('me', null, studentCookie)).status, 401);
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    if (mongoose.connection.readyState === 1) await mongoose.connection.dropDatabase();
    if (app?.locals.sessionStore) await app.locals.sessionStore.close();
    await mongoose.disconnect();
  }
});
