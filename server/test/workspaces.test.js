const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { randomBytes } = require('node:crypto');
require('dotenv').config({ path: require('node:path').join(__dirname, '../.env'), quiet: true });
const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');

test('private draft workspaces, team invitations and atomic single-team membership', { timeout: 60000 }, async () => {
  process.env.SESSION_SECRET = randomBytes(48).toString('hex');
  let app, server;
  try {
    await mongoose.connect(process.env.MONGODB_URI, { dbName: `synoria_workspace_${randomBytes(8).toString('hex')}`, serverSelectionTimeoutMS: 5000 });
    const Department = require('../src/models/department');
    const Student = require('../src/models/student');
    const Workspace = require('../src/models/workspace');
    const Supervisor = require('../src/models/supervisor');
    const Examiner = require('../src/models/examiner');
    await Promise.all([Department, Student, Workspace, Supervisor, Examiner].map(Model => Model.init()));
    const password = 'workspace-password-123';
    const passwordHash = await bcrypt.hash(password, 12);
    const departments = await Department.create(['CSE', 'EEE'].map(name => ({ proposalPeriod: { status: 'open', deadline: new Date(Date.now()+86400000) }, name, university: 'Test University', email: `${name}@example.edu`, passwordHash })));
    const students = await Student.create(Array.from({ length: 8 }, (_, i) => ({ department: departments[i === 7 ? 1 : 0]._id, name: `Student ${i}`, email: `student${i}@example.edu`, phone: '+8801712345678', studentId: `ID-${i}`, passwordHash })));
    const supervisor = await Supervisor.create({ department: departments[0]._id, name: 'Supervisor', email: 'supervisor@example.edu', phone: '+8801712345678', passwordHash });
    const examiner = await Examiner.create({ department: departments[0]._id, name: 'Examiner', email: 'examiner@example.edu', phone: '+8801712345678', passwordHash });
    app = require('../src'); server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
    const base = `http://127.0.0.1:${server.address().port}/api/auth`;
    const request = (path, body, cookie, method) => fetch(`${base}/${path}`, { method: method || (body ? 'POST' : 'GET'), headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: body ? JSON.stringify(body) : undefined });
    const login = async (account, role = 'student') => {
      const response = await request('login', { email: account.email, password, role });
      assert.equal(response.status, 200);
      return response.headers.get('set-cookie').split(';')[0];
    };
    const cookies = [];
    for (const student of students) cookies.push(await login(student));
    assert.equal((await request('workspaces')).status, 401);
    for (const [account, role] of [[departments[0], 'department'], [supervisor, 'supervisor'], [examiner, 'examiner']]) {
      const cookie = await login(account, role);
      assert.equal((await request('workspaces', null, cookie)).status, 403);
      assert.equal((await request('workspaces', { name: 'Denied', workType: 'project' }, cookie)).status, 403);
    }
    const create = (i, name = `Workspace ${i}`, type = 'project') => request('workspaces', { name, workType: type, department: departments[1].id, leader: students[7].id, members: [students[7].id], status: 'active' }, cookies[i]);
    assert.equal((await create(0, '   ')).status, 400);
    assert.equal((await create(0, 'Invalid', 'unknown')).status, 400);
    const first = await create(0);
    assert.equal(first.status, 201);
    const teamA = (await first.json()).workspace;
    assert.equal(teamA.leaderId, students[0].id);
    assert.equal(teamA.status, 'draft');
    assert.equal(teamA.members.length, 1);
    assert.equal(teamA.members[0].passwordHash, undefined);
    assert.equal(String((await Workspace.findById(teamA.id)).department), departments[0].id);
    assert.equal((await create(0)).status, 409);
    const parallelCreate = await Promise.all([create(4), create(4)]);
    assert.deepEqual(parallelCreate.map(r => r.status).sort(), [201, 409]);
    const teamB = (await (await create(1, 'Thesis Team', 'thesis')).json()).workspace;
    const teamC = (await (await create(5, 'Research Team', 'research')).json()).workspace;
    const path = id => `workspaces/${id}`;
    assert.equal((await request(path(teamA.id), null, cookies[2])).status, 404);
    assert.equal((await request(path(teamA.id), null, cookies[7])).status, 404);
    assert.equal((await request('workspaces/not-an-id', null, cookies[0])).status, 404);
    const invite = async (team, leader, student) => {
      const response = await request(`${path(team.id)}/invitations`, { email: students[student].email }, cookies[leader]);
      assert.equal(response.status, 201, await response.clone().text());
      const updated = (await response.json()).workspace;
      return updated.invitations.filter(item => item.student.id === students[student].id).at(-1);
    };
    const respond = (team, invitation, student, action = 'accept') => request(`${path(team.id)}/invitations/${invitation.id}`, { action }, cookies[student], 'PATCH');
    assert.equal((await request(`${path(teamA.id)}/invitations`, { email: students[7].email }, cookies[0])).status, 404);
    assert.equal((await request(`${path(teamA.id)}/invitations`, { email: students[0].email }, cookies[0])).status, 409);
    assert.equal((await request(`${path(teamA.id)}/invitations`, { email: students[4].email }, cookies[0])).status, 409);
    const invitationA = await invite(teamA, 0, 2);
    assert.equal((await request(`${path(teamA.id)}/invitations`, { email: students[2].email }, cookies[0])).status, 409);
    const invitationB = await invite(teamB, 1, 2);
    const inbox = await (await request('workspaces', null, cookies[2])).json();
    assert.equal(inbox.workspace, null);
    assert.equal(inbox.invitations.length, 2);
    assert.equal(inbox.invitations[0].members, undefined);
    assert.equal((await respond(teamA, invitationA, 3)).status, 404);
    assert.equal((await respond(teamA, invitationA, 7)).status, 404);
    const acceptRace = await Promise.all([respond(teamA, invitationA, 2), respond(teamB, invitationB, 2)]);
    assert.deepEqual(acceptRace.map(r => r.status).sort(), [200, 409]);
    assert.equal(await Workspace.countDocuments({ members: students[2]._id, isActive: true }), 1);
    const joined = (await (await request('workspaces', null, cookies[2])).json()).workspace;
    const winning = joined.id === teamA.id ? teamA : teamB;
    const losing = joined.id === teamA.id ? teamB : teamA;
    const leaderIndex = joined.id === teamA.id ? 0 : 1;
    const losingLeader = leaderIndex === 0 ? 1 : 0;
    const winningInvite = joined.id === teamA.id ? invitationA : invitationB;
    const losingInvite = joined.id === teamA.id ? invitationB : invitationA;
    assert.equal(joined.members.length, 2);
    assert.equal(joined.invitations.length, 0);
    assert.equal((await respond(winning, winningInvite, 2)).status, 404);
    assert.equal((await request(path(losing.id), null, cookies[2])).status, 404);
    assert.equal((await respond(losing, losingInvite, 2, 'decline')).status, 200);
    assert.equal((await respond(losing, losingInvite, 2, 'accept')).status, 404);
    const another = await invite(winning, leaderIndex, 3);
    assert.equal((await respond(winning, another, leaderIndex, 'cancel')).status, 200);
    assert.equal((await respond(winning, another, 3)).status, 404);
    const retry = await invite(winning, leaderIndex, 3);
    const repeatedAccept = await Promise.all([respond(winning, retry, 3), respond(winning, retry, 3)]);
    assert.deepEqual(repeatedAccept.map(r => r.status).sort(), [200, 404]);
    assert.equal((await Workspace.findById(winning.id)).members.filter(id => String(id) === students[3].id).length, 1);
    assert.equal((await request(`${path(winning.id)}/invitations`, { email: students[6].email }, cookies[2])).status, 403);
    assert.equal((await request(path(winning.id), { name: 'Hijack', workType: 'thesis' }, cookies[2], 'PATCH')).status, 403);
    assert.equal((await request(path(winning.id), { name: 'Renamed Team', workType: 'research', leader: students[2].id, members: [] }, cookies[leaderIndex], 'PATCH')).status, 200);
    assert.equal(String((await Workspace.findById(winning.id)).leader), students[leaderIndex].id);
    const remove = (team, actor, target) => request(`${path(team.id)}/members/${students[target].id}`, {}, cookies[actor], 'DELETE');
    assert.equal((await remove(winning, 2, 3)).status, 403);
    assert.equal((await remove(winning, leaderIndex, leaderIndex)).status, 409);
    assert.equal((await remove(winning, 7, 2)).status, 404);
    assert.equal((await remove(winning, 2, 2)).status, 200);
    assert.equal((await request(path(winning.id), null, cookies[2])).status, 404);
    assert.equal((await create(2, 'New Solo Team')).status, 201);
    assert.equal((await remove(winning, leaderIndex, 3)).status, 200);
    assert.equal((await request(path(winning.id), null, cookies[3])).status, 404);
    // Accept versus creating a workspace must have only one winner as well.
    const invitationC = await invite(teamC, 5, 6);
    const acceptCreateRace = await Promise.all([respond(teamC, invitationC, 6), create(6)]);
    assert.equal(acceptCreateRace.filter(response => response.status === 200 || response.status === 201).length, 1);
    assert.equal(acceptCreateRace.filter(response => response.status === 409).length, 1);
    assert.equal(await Workspace.countDocuments({ members: students[6]._id, isActive: true }), 1);
    const lockInvite = await invite(losing, losingLeader, 3);
    await Workspace.updateOne({ _id: losing.id }, { $set: { status: 'submitted' } });
    assert.equal((await respond(losing, lockInvite, 3)).status, 200);
    assert.equal((await request(path(losing.id), { name: 'Updated Submitted Team' }, cookies[losingLeader], 'PATCH')).status, 200);
    assert.equal((await request(`${path(losing.id)}/invitations`, { email: students[3].email }, cookies[losingLeader])).status, 409);
    assert.equal((await remove(losing, 3, 3)).status, 200);
    await Workspace.updateOne({ _id: winning.id }, { $set: { status: 'submitted' }, $addToSet: { members: students[3]._id } });
    assert.equal((await remove(winning, 3, 3)).status, 200);
    assert.equal((await remove(winning, leaderIndex, 3)).status, 404);
    // Deactivation must also block workspace APIs, not only /me.
    await Student.updateOne({ _id: students[leaderIndex]._id }, { $set: { isActive: false }, $inc: { authVersion: 1 } });
    assert.equal((await request('workspaces', null, cookies[leaderIndex])).status, 401);
    assert.equal((await request(path(winning.id), null, cookies[leaderIndex])).status, 401);
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    if (mongoose.connection.readyState === 1) await mongoose.connection.dropDatabase();
    if (app?.locals.sessionStore) await app.locals.sessionStore.close();
    await mongoose.disconnect();
  }
});
