const validateRequest = require('../middleware/validateRequest');
const chat = require('../controllers/chatController');
const router = require('express').Router();
const proposal = require('../controllers/proposalController');
const controller = require('../controllers/workspaceController');
router.use(require('../middleware/requireStudent'));
router.get('/teams', validateRequest, controller.listTeams);
router.post('/:id/members', validateRequest, controller.addMember);
router.patch('/:id/members/:studentId', validateRequest, controller.editRole);
router.post('/:id/joinRequests', validateRequest, controller.requestJoin);
router.patch('/:id/joinRequests/:requestId', validateRequest, controller.respondToJoin);
router.get('/', validateRequest, controller.overview);
router.post('/', validateRequest, controller.createWorkspace);
router.get('/:id/proposal', validateRequest, proposal.getProposal);
router.patch('/:id/proposal', validateRequest, proposal.saveDraft);
router.post('/:id/proposal/scopeChange', validateRequest, require('../controllers/proposalReviewController').scopeChange);
router.post('/:id/proposal/submit', validateRequest, proposal.submitProposal);
const meetings = require('../controllers/chatMeetingController');
router.get('/:id/chat/meetings', validateRequest, meetings.read);
router.post('/:id/chat/meetings', validateRequest, meetings.save);
router.patch('/:id/chat/meetings/:meetingId', validateRequest, meetings.save);
router.get('/:id/chat', validateRequest, chat.messages);
router.post('/:id/chat', validateRequest, chat.send);
router.post('/:id/chat/read', validateRequest, chat.read);
router.get('/:id', validateRequest, controller.getWorkspace);
router.patch('/:id', validateRequest, controller.editWorkspace);
router.post('/:id/invitations', validateRequest, controller.inviteStudent);
router.patch('/:id/invitations/:invitationId', validateRequest, controller.respondToInvitation);
router.delete('/:id/members/:studentId', validateRequest, controller.removeMember);
module.exports = router;
